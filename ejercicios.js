// ============================================
// EJERCICIO 1: EL TERRENO RECTANGULAR
// Un agricultor quiere calcular el área y el perímetro de su terreno
// ============================================

// Declaramos la base y la altura del terreno
let base = 10;
let altura = 5;

// Calculamos el área (base * altura)
let area = base * altura;

// Calculamos el perímetro (2 * (base + altura))
let perimetro = 2 * (base + altura);

// Mostramos los resultados en la consola
console.log("Ejercicio 1: Terreno rectangular");
console.log("Área:", area);
console.log("Perímetro:", perimetro);


// ============================================
// EJERCICIO 2: PROMEDIO DEL ESTUDIANTE
// Se calculan tres notas y se obtiene el promedio
// ============================================

// Declaramos las tres notas
let nota1 = 4.0;
let nota2 = 3.5;
let nota3 = 4.5;

// Calculamos el promedio de las tres notas
let promedio = (nota1 + nota2 + nota3) / 3;

// Mostramos el resultado en la consola
console.log("Ejercicio 2: Promedio del estudiante");
console.log("Promedio:", promedio);


// ============================================
// EJERCICIO 4: CONTADOR DE VISITAS
// Se realizan operaciones de asignación sobre un contador
// ============================================

// El contador inicia en 100 visitas
let visitas = 100;

// Se suman 25 visitas nuevas
visitas += 25;

// Se restan 10 visitas por error de registro
visitas -= 10;

// Finalmente se duplican las visitas
visitas *= 2;

// Mostramos el resultado final
console.log("Ejercicio 4: Contador de visitas");
console.log("Visitas finales:", visitas);


